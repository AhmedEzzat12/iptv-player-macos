def _day_slots(tvg: str, day: int) -> list[tuple[int, int]]:
    rng = random.Random(f"{tvg}/{day}")
    t, end, out = day, day + 86400, []
    while t < end:
        remaining = (end - t) // 60
        minutes = rng.choice((30, 30, 45, 60, 60))
        if remaining <= 60:
            minutes = remaining
        elif remaining - minutes < 30:
            minutes = remaining - 30
        out.append((t, t + minutes * 60))
        t += minutes * 60
    return out


def programmes(tvg: str, lo: float, hi: float, base: str, slug: str | None, channel_name: str) -> list[dict]:
    show = EPG_SHOWS[tvg]
    out = []
    day = int(lo // 86400) * 86400
    while day < hi:
        for start, stop in _day_slots(tvg, day):
            if stop <= lo or start >= hi:
                continue
            rng = random.Random(f"{tvg}@{start}")
            title = rng.choice(show["titles"])
            minutes = (stop - start) // 60
            hhmm = lambda e: time.strftime("%H:%M", time.gmtime(e))  # noqa: E731
            prog = {
                "start": start, "stop": stop, "title": title,
                "subtitle": rng.choice(show["subtitles"]) if rng.random() < 0.7 else None,
                "desc": f"{title} on {channel_name}. Airs {hhmm(start)}-{hhmm(stop)} UTC ({minutes} min). "
                        f"{rng.choice(FLAVOR)}",
                "categories": show["categories"],
                "icon": f"{base}/img/{IMG['feed_backdrop'](slug)}" if slug and rng.random() < 0.35 else None,
                "season": rng.randint(1, 6), "episode": rng.randint(1, 24),
                "with_episode": tvg in ("kids.tuner", "sports.tuner", "news.tuner") and rng.random() < 0.6,
                "new": rng.random() < 0.25,
                "rating": show["rating"],
                "credits": tvg == "movies.tuner",
            }
            out.append(prog)
        day += 86400
    return out


def xmltv(base: str) -> bytes:
    now = time.time()
    lo, hi = now - 12 * 3600, now + 36 * 3600
    stamp = lambda e: time.strftime("%Y%m%d%H%M%S +0000", time.gmtime(e))  # noqa: E731
    attr = lambda v: escape(v, {'"': "&quot;"})  # noqa: E731
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!DOCTYPE tv SYSTEM "xmltv.dtd">',
           f'<!-- Tuner test kit guide, generated {fmt_utc(now)}; window now-12h .. now+36h -->',
           '<tv generator-info-name="Tuner Test Kit" source-info-name="local">']
    for tvg, name, extra, slug in EPG_CHANNELS:
        out.append(f'  <channel id="{attr(tvg)}">')
        for display in [name, *extra]:
            out.append(f'    <display-name lang="en">{escape(display)}</display-name>')
        if slug:
            out.append(f'    <icon src="{attr(base)}/img/{IMG["logo"](slug)}"/>')
        out.append("  </channel>")
    for tvg, name, _, slug in EPG_CHANNELS:
        for p in programmes(tvg, lo, hi, base, slug, name):
            out.append(f'  <programme start="{stamp(p["start"])}" stop="{stamp(p["stop"])}" channel="{attr(tvg)}">')
            out.append(f'    <title lang="en">{escape(p["title"])}</title>')
            if p["subtitle"]:
                out.append(f'    <sub-title lang="en">{escape(p["subtitle"])}</sub-title>')
            out.append(f'    <desc lang="en">{escape(p["desc"])}</desc>')
            if p["credits"]:
                out.append("    <credits><director>Rhea Tester</director><actor>Bun E. Rabbit</actor>"
                           "<actor>Stereo Jones</actor></credits>")
            for c in p["categories"]:
                out.append(f'    <category lang="en">{escape(c)}</category>')
            if p["icon"]:
                out.append(f'    <icon src="{attr(p["icon"])}"/>')
            if p["with_episode"]:
                out.append(f'    <episode-num system="xmltv_ns">{p["season"] - 1}.{p["episode"] - 1}.0/1</episode-num>')
                out.append(f'    <episode-num system="onscreen">S{p["season"]:02d}E{p["episode"]:02d}</episode-num>')
            if p["new"]:
                out.append("    <new/>")
            else:
                out.append("    <previously-shown/>")
            out.append(f'    <rating system="VCHIP"><value>{p["rating"]}</value></rating>')
            out.append("  </programme>")
    out.append("</tv>")
    return ("\n".join(out) + "\n").encode("utf-8")


