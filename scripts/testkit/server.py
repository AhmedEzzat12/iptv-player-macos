R_STREAM = re.compile(r"/(stream|ua|flaky)/(\d+)\.(ts|m3u8)")
R_HLSSEG = re.compile(r"/hlsseg/(\d+)/(-?\d+)\.ts")
R_HLSVOD = re.compile(r"/hls/(\d+)/([\w.\-]+)")
R_LIVE = re.compile(r"/live/([^/]+)/([^/]+)/(\d+)(?:\.(\w+))?")
R_MOVIE = re.compile(r"/movie/([^/]+)/([^/]+)/(\d+)(?:\.(\w+))?")
R_SERIES = re.compile(r"/series/([^/]+)/([^/]+)/(\d+)(?:\.(\w+))?")
R_TIMESHIFT = re.compile(r"/timeshift/([^/]+)/([^/]+)/(\d+)/([^/]+)/(\d+)\.(ts|m3u8)")
R_SHORT_LIVE = re.compile(r"/([^/]+)/([^/]+)/(\d+)(?:\.(ts|m3u8))?")
R_IMG = re.compile(r"/img/(.+)")


def route(h: Handler) -> None:  # noqa: C901 - a flat routing table reads best here
    p, q, base = h.route_path, h.query, h.base

    if p in ("/", "/index.html"):
        return h.send_text(200, index_page(base), note="index")
    if p == "/playlist.m3u":
        return h.respond(200, m3u_playlist(base).encode(), CONTENT_TYPES[".m3u"], note="m3u playlist")
    if p == "/epg.xml":
        return h.respond(200, xmltv(base), "application/xml; charset=utf-8", note="xmltv")
    if p == "/epg.xml.gz":
        return h.respond(200, gzip.compress(xmltv(base), mtime=0), CONTENT_TYPES[".gz"], note="xmltv gz")
    if p.startswith("/dead/"):
        return h.send_text(404, "Stream not found (deliberately dead test channel)\n")

    if m := R_STREAM.fullmatch(p):
        kind, n, ext = m.group(1), int(m.group(2)), m.group(3)
        if kind == "ua":
            ua = h.headers.get("User-Agent", "")
            ref = h.headers.get("Referer", "")
            ref_note = "referer ok" if ref == LOCKED_REFERRER else f"referer {'missing' if not ref else 'WRONG: ' + ref}"
            if LOCKED_UA_TOKEN not in ua:
                return h.send_text(403, f"Forbidden: User-Agent must contain '{LOCKED_UA_TOKEN}' ({ref_note})\n")
            return h.serve_feed(n, ext, f"ua-locked: UA ok, {ref_note};")
        return h.serve_feed(n, ext, kind, flaky=(kind == "flaky"))

    if m := R_HLSSEG.fullmatch(p):
        n, j = int(m.group(1)), int(m.group(2))
        if n not in FEEDS:
            return h.send_text(404, "no such channel\n")
        return h.send_bytes_ranged(hls_feed(n).segment_bytes(j), "video/mp2t", note=f"feed={n} seg={j}")
    if m := R_HLSVOD.fullmatch(p):
        n = int(m.group(1))
        if n not in FEEDS:
            return h.send_text(404, "no such channel\n")
        return h.send_file(feed_hls_dir(n) / m.group(2), note="static hls")
    if m := R_IMG.fullmatch(p):
        img_root = (MEDIA / "img").resolve()
        target = (img_root / m.group(1)).resolve()
        if not target.is_relative_to(img_root):
            return h.send_text(404, "not found\n")
        return h.send_file(target)

    # ---- Xtream Codes ----
    if p == "/player_api.php":
        if not check_creds(q.get("username"), q.get("password")):
            return h.send_json({"user_info": {"auth": 0}}, note="AUTH FAILED")
        action = q.get("action", "")
        cat = q.get("category_id") or None
        if action == "":
            host, port = h.host_port
            data = xtream_login(host.strip("[]"), port)
        elif action == "get_live_categories":
            data = [{"category_id": c, "category_name": n, "parent_id": 0} for c, n in LIVE_CATEGORIES]
        elif action == "get_live_streams":
            data = xtream_live_streams(base, cat)
        elif action == "get_vod_categories":
            data = [{"category_id": c, "category_name": n, "parent_id": 0} for c, n in VOD_CATEGORIES]
        elif action == "get_vod_streams":
            data = xtream_vod_streams(base, cat)
        elif action == "get_vod_info":
            data = xtream_vod_info(base, q.get("vod_id", ""))
        elif action == "get_series_categories":
            data = [{"category_id": c, "category_name": n, "parent_id": 0} for c, n in SERIES_CATEGORIES]
        elif action == "get_series":
            data = xtream_series(base, cat)
        elif action == "get_series_info":
            data = xtream_series_info(base, q.get("series_id", ""))
        elif action in ("get_short_epg", "get_simple_data_table"):
            limit = q.get("limit", "")
            data = xtream_short_epg(base, q.get("stream_id", ""),
                                    int(limit) if limit.isdigit() else (4 if action == "get_short_epg" else 50))
        else:
            data = []
        return h.send_json(data, note=f"xtream {action or 'login'}")
    if p == "/xmltv.php":
        if not check_creds(q.get("username"), q.get("password")):
            return h.send_text(401, "Unauthorized\n")
        return h.respond(200, xmltv(base), "application/xml; charset=utf-8", note="xtream xmltv")
    if p == "/get.php":
        if not check_creds(q.get("username"), q.get("password")):
            return h.send_text(401, "Unauthorized\n")
        kind = q.get("type", "m3u_plus")
        body = xtream_m3u(base, plus=(kind != "m3u"), output=q.get("output", "ts")).encode()
        return h.respond(200, body, CONTENT_TYPES[".m3u"],
                         [("Content-Disposition", 'attachment; filename="playlist.m3u"')], note=f"xtream {kind}")
    if p == "/streaming/timeshift.php":
        if not check_creds(q.get("username"), q.get("password")):
            return h.send_text(401, "Unauthorized\n")
        return serve_timeshift(h, q.get("stream", ""), q.get("start", ""), q.get("duration", "60"), "ts")
    if m := R_LIVE.fullmatch(p):
        return serve_xtream_live(h, *m.groups())
    if m := R_MOVIE.fullmatch(p):
        user, pw, vid, ext = m.groups()
        if not check_creds(user, pw):
            return h.send_text(401, "Unauthorized\n")
        movie = next((x for x in MOVIES if str(x["id"]) == vid), None)
        if not movie:
            return h.send_text(404, f"no such movie {vid}\n")
        note = f"movie {movie['title']}" + (f" (asked .{ext}, serving .{movie['ext']})" if ext and ext != movie["ext"] else "")
        return h.send_file(MEDIA / movie["file"], note=note)
    if m := R_SERIES.fullmatch(p):
        user, pw, eid, ext = m.groups()
        if not check_creds(user, pw):
            return h.send_text(401, "Unauthorized\n")
        found = all_episodes().get(int(eid))
        if not found:
            return h.send_text(404, f"no such episode {eid}\n")
        s, ep = found
        return h.send_file(MEDIA / ep["file"], note=f"episode {s['title']} S{ep['season']:02d}E{ep['episode']:02d}")
    if m := R_TIMESHIFT.fullmatch(p):
        user, pw, minutes, start, sid, ext = m.groups()
        if not check_creds(user, pw):
            return h.send_text(401, "Unauthorized\n")
        return serve_timeshift(h, sid, start, minutes, ext)
    if (m := R_SHORT_LIVE.fullmatch(p)) and check_creds(m.group(1), m.group(2)):
        return serve_xtream_live(h, *m.groups())
    return h.send_text(404, f"not found: {p}\n")


def serve_xtream_live(h: Handler, user: str, pw: str, sid: str, ext: str | None) -> None:
    if not check_creds(user, pw):
        return h.send_text(401, "Unauthorized\n")
    s = next((s for s in XTREAM_LIVE if str(s["id"]) == sid), None)
    if not s:
        return h.send_text(404, f"no such stream {sid}\n")
    if not s["feed"]:
        return h.send_text(404, f"Stream not found (stream {sid} is deliberately dead)\n")
    ext = (ext or "ts").lower()
    if ext not in ("ts", "m3u8"):
        return h.send_text(404, f"unsupported live format .{ext}\n")
    return h.serve_feed(s["feed"], ext, f"xtream live {s['id']}")


def serve_timeshift(h: Handler, sid: str, start_text: str, minutes: str, ext: str) -> None:
    s = next((s for s in XTREAM_LIVE if str(s["id"]) == sid), None)
    if not s or not s["feed"]:
        return h.send_text(404, f"no archive for stream {sid}\n")
    start = parse_timeshift_start(start_text)
    if start is None:
        return h.send_text(400, f"bad timeshift start '{start_text}' (want YYYY-MM-DD:HH-MM, server-local)\n")
    try:
        mins = max(1, int(minutes))
    except ValueError:
        return h.send_text(400, f"bad duration '{minutes}'\n")
    return h.serve_archive(s["feed"], ext, start, mins * 60, f"xtream timeshift {sid}")


