    cats = dict(LIVE_CATEGORIES)
    lines = [f'#EXTM3U url-tvg="{base}/xmltv.php?username={USERNAME}&password={PASSWORD}"' if plus else "#EXTM3U"]

    def add(attrs, title, url):
        lines.append(_extinf(attrs, title) if plus else f"#EXTINF:-1,{title}")
        lines.append(url)

    for s in XTREAM_LIVE:
        tvg, slug = _live_tvg_logo(s)
        attrs = [("tvg-id", tvg), ("tvg-name", s["name"]), ("tvg-logo", f"{base}/img/{IMG['logo'](slug)}"),
                 ("group-title", cats[s["category"]])]
        if s["archive"]:
            attrs.append(("tvg-rec", str(s["archive"])))
        add(attrs, s["name"], f"{base}/live/{USERNAME}/{PASSWORD}/{s['id']}.{ext}")
    vcats = dict(VOD_CATEGORIES)
    for m in MOVIES:
        name = f"{m['title']} ({m['year']})"
        add([("tvg-id", ""), ("tvg-name", name), ("tvg-logo", f"{base}/img/{IMG['movie_poster'](m['id'])}"),
             ("group-title", vcats[m["category"]])], name, f"{base}/movie/{USERNAME}/{PASSWORD}/{m['id']}.{m['ext']}")
