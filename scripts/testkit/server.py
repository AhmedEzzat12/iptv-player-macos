# --------------------------------------------------------------------------------------------------
# MPEG-TS handling: scanning, loop rewriting (PTS/DTS/PCR + continuity counters)
# --------------------------------------------------------------------------------------------------

TS_PACKET = 188
PTS_WRAP = 1 << 33


class MediaMissing(Exception):
    pass


def _read_pts(b, o: int) -> int:
    return (((b[o] >> 1) & 0x07) << 30) | (b[o + 1] << 22) | ((b[o + 2] >> 1) << 15) | (b[o + 3] << 7) | (b[o + 4] >> 1)


def _write_pts(b: bytearray, o: int, v: int) -> None:
    b[o] = (b[o] & 0xF0) | ((v >> 29) & 0x0E) | 0x01
    b[o + 1] = (v >> 22) & 0xFF
    b[o + 2] = ((v >> 14) & 0xFE) | 0x01
    b[o + 3] = (v >> 7) & 0xFF
    b[o + 4] = ((v << 1) & 0xFE) | 0x01


def _read_pcr27(b, o: int) -> int:
    base = (b[o] << 25) | (b[o + 1] << 17) | (b[o + 2] << 9) | (b[o + 3] << 1) | (b[o + 4] >> 7)
    ext = ((b[o + 4] & 0x01) << 8) | b[o + 5]
    return base * 300 + ext


class TSBuffer:
    """An MPEG-TS file in memory plus the byte offsets needed to re-time it cheaply."""

    def __init__(self, data: bytes, label: str):
        n = len(data) // TS_PACKET
        if n == 0 or data[0] != 0x47:
            raise ValueError(f"{label}: not an MPEG-TS file")
        d = data if len(data) == n * TS_PACKET else data[: n * TS_PACKET]
        self.label = label
        self.data = d
        self.n = n
        self.cc_offsets = array("L")
        self.cc_pids = array("H")
        self.pcr_offsets = array("L")
        self.pts_offsets = array("L")
        self.payload_counts: dict[int, int] = {}
        self.pkt_time = array("d", [0.0]) * n     # seconds since the first PCR (step function)
        self.keyframes: list[int] = []
        self.pats: list[int] = []
        video_starts: list[int] = []
        pts_by_stream: dict[int, list[int]] = {}
        first_pcr = None
        t = 0.0
        for i in range(n):
            o = i * TS_PACKET
            if d[o] != 0x47:
                raise ValueError(f"{label}: lost sync at packet {i}")
            b1 = d[o + 1]
            pid = ((b1 & 0x1F) << 8) | d[o + 2]
            afc = (d[o + 3] >> 4) & 3
            p = o + 4
            rai = False
            if afc & 2:
                alen = d[o + 4]
                if alen:
                    flags = d[o + 5]
                    rai = bool(flags & 0x40)
                    if flags & 0x10 and alen >= 7:
                        pcr = _read_pcr27(d, o + 6)
                        if first_pcr is None:
                            first_pcr = pcr
                        t = (pcr - first_pcr) / 27_000_000
                        self.pcr_offsets.append(o + 6)
                p = o + 5 + alen
            self.pkt_time[i] = t
            if not afc & 1:
                continue
            self.cc_offsets.append(o + 3)
            self.cc_pids.append(pid)
            self.payload_counts[pid] = self.payload_counts.get(pid, 0) + 1
            if not b1 & 0x40:
                continue
            if pid == 0:
                self.pats.append(i)
                continue
            end = o + TS_PACKET
            if p + 14 <= end and d[p] == 0 and d[p + 1] == 0 and d[p + 2] == 1:
                sid = d[p + 3]
                if sid == 0xBD or 0xC0 <= sid <= 0xEF:
                    flags2 = d[p + 7] >> 6
                    if flags2 & 2:
                        self.pts_offsets.append(p + 9)
                        if flags2 == 3 and p + 19 <= end:
                            self.pts_offsets.append(p + 14)
                        pts_by_stream.setdefault(sid, []).append(_read_pts(d, p + 9))
                        if sid >= 0xE0:
                            video_starts.append(i)
                            if rai:
                                self.keyframes.append(i)
        if not self.keyframes:
            self.keyframes = video_starts or [0]
        self.kf_times = [self.pkt_time[i] for i in self.keyframes]
        # Per elementary stream: (first PTS, last PTS, frame duration) in 90 kHz ticks.
        self.spans: dict[int, tuple[int, int, int]] = {}
        for sid, values in pts_by_stream.items():
            uniq = sorted(set(values))
            diffs = [b - a for a, b in zip(uniq, uniq[1:])]
            self.spans[sid] = (uniq[0], uniq[-1], min(diffs) if diffs else 0)

    def shifted(self, shift90: int, cc_add: dict[int, int]) -> bytes:
        """Copy with every PTS/DTS/PCR moved by ``shift90`` (90 kHz) and continuity counters advanced."""
        cc_add = {pid: v % 16 for pid, v in cc_add.items() if v % 16}
        shift90 %= PTS_WRAP
        if not shift90 and not cc_add:
            return self.data
        b = bytearray(self.data)
        if cc_add:
            for off, pid in zip(self.cc_offsets, self.cc_pids):
                add = cc_add.get(pid)
                if add:
                    v = b[off]
                    b[off] = (v & 0xF0) | ((v + add) & 0x0F)
        if shift90:
            for off in self.pcr_offsets:
                base = (b[off] << 25) | (b[off + 1] << 17) | (b[off + 2] << 9) | (b[off + 3] << 1) | (b[off + 4] >> 7)
                base = (base + shift90) % PTS_WRAP
                b[off] = (base >> 25) & 0xFF
                b[off + 1] = (base >> 17) & 0xFF
                b[off + 2] = (base >> 9) & 0xFF
                b[off + 3] = (base >> 1) & 0xFF
                b[off + 4] = ((base & 1) << 7) | (b[off + 4] & 0x7F)
            for off in self.pts_offsets:
                _write_pts(b, off, (_read_pts(b, off) + shift90) % PTS_WRAP)
        return bytes(b)


def loop_period90(buffers: list[TSBuffer]) -> int:
    """Loop length in 90 kHz ticks: video span (first..last PTS) plus one frame duration.

    Video carries one frame per PES, so its frame duration is exact; audio PES packets bundle several
    AAC frames, so audio is only used when there is no video. make_media.sh trims looping clips so
    their audio (including the AAC priming frame) ends exactly where the video does.
    """
    sids = {sid for b in buffers for sid in b.spans}
    video = [sid for sid in sids if sid >= 0xE0]
    period = 0
    for sid in video or sids:
        spans = [b.spans[sid] for b in buffers if sid in b.spans]
        frames = [f for _, _, f in spans if f]
        period = max(period, max(hi for _, hi, _ in spans) - min(lo for lo, _, _ in spans) + (min(frames) if frames else 0))
    if not period:
        raise ValueError("no timestamps found in " + ", ".join(b.label for b in buffers))
    return period


class LiveFeed:
    """A channel clip looped forever on a virtual timeline that starts at ANCHOR."""

    def __init__(self, n: int):
        path = feed_ts_path(n)
        if not path.is_file():
            raise MediaMissing(f"missing {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
        self.n = n
        self.ts = TSBuffer(path.read_bytes(), path.name)
        self.period90 = loop_period90([self.ts])
        self.period = self.period90 / 90000
        self.loop_size = self.ts.n * TS_PACKET

    def loop_bytes(self, loop: int) -> bytes:
        return _feed_loop(self.n, loop)

    def build_loop(self, loop: int) -> bytes:
        return self.ts.shifted(loop * self.period90, {pid: loop * c for pid, c in self.ts.payload_counts.items()})

    def join_point(self, vtime: float) -> int:
        """Absolute packet index to start a client at: the PAT before the last keyframe <= vtime."""
        loop = math.floor(vtime / self.period)
        within = vtime - loop * self.period
        k = bisect.bisect_right(self.ts.kf_times, within) - 1
        if k < 0:
            loop -= 1
            k = len(self.ts.keyframes) - 1
        kf = self.ts.keyframes[k]
        j = bisect.bisect_right(self.ts.pats, kf) - 1
        start = self.ts.pats[j] if j >= 0 else kf
        return loop * self.ts.n + start


class HLSFeed:
    """The pre-segmented HLS rendition of a channel, served as an endless live window."""

    def __init__(self, n: int):
        folder = feed_hls_dir(n)
        index = folder / "index.m3u8"
        if not index.is_file():
            raise MediaMissing(f"missing {index}")
        self.n = n
        self.durations: list[float] = []
        names: list[str] = []
        pending = None
        for line in index.read_text().splitlines():
            line = line.strip()
            if line.startswith("#EXTINF:"):
                pending = float(line[8:].split(",")[0])
            elif line and not line.startswith("#") and pending is not None:
                self.durations.append(pending)
                names.append(line)
                pending = None
        if not names:
            raise MediaMissing(f"{index} lists no segments")
        self.segments = [TSBuffer((folder / name).read_bytes(), name) for name in names]
        self.period90 = loop_period90(self.segments)
        self.cc_counts: dict[int, int] = {}
        for s in self.segments:
            for pid, c in s.payload_counts.items():
                self.cc_counts[pid] = self.cc_counts.get(pid, 0) + c
        self.cum = [0.0]
        for d in self.durations:
            self.cum.append(self.cum[-1] + d)
        self.period = self.cum[-1]
        self.count = len(names)
        self.target = max(1, max(int(d + 0.5) for d in self.durations))

    def segment_bytes(self, j: int) -> bytes:
        return _hls_segment(self.n, j)

    def build_segment(self, j: int) -> bytes:
        loop, k = divmod(j, self.count)
        return self.segments[k].shifted(loop * self.period90, {pid: loop * c for pid, c in self.cc_counts.items()})

    def segment_at(self, vtime: float) -> int:
        loop = math.floor(vtime / self.period)
        within = vtime - loop * self.period
        k = min(self.count - 1, max(0, bisect.bisect_right(self.cum, within) - 1))
        return loop * self.count + k

    def segment_start(self, j: int) -> float:
        loop, k = divmod(j, self.count)
        return loop * self.period + self.cum[k]

    def playlist(self, first: int, count: int, *, live: bool, media_sequence: int) -> str:
        lines = ["#EXTM3U", "#EXT-X-VERSION:3", f"#EXT-X-TARGETDURATION:{self.target}"]
        if not live:
            lines.append("#EXT-X-PLAYLIST-TYPE:VOD")
        lines.append(f"#EXT-X-MEDIA-SEQUENCE:{media_sequence}")
        for j in range(first, first + count):
            pdt = dt.datetime.fromtimestamp(ANCHOR + self.segment_start(j), dt.timezone.utc)
            lines.append("#EXT-X-PROGRAM-DATE-TIME:" + pdt.isoformat(timespec="milliseconds").replace("+00:00", "Z"))
            lines.append(f"#EXTINF:{self.durations[j % self.count]:.3f},")
            lines.append(f"/hlsseg/{self.n}/{j}.ts")
        if not live:
            lines.append("#EXT-X-ENDLIST")
        return "\n".join(lines) + "\n"


_registry_lock = threading.Lock()
_registry: dict[tuple[str, int], object] = {}


def live_feed(n: int) -> LiveFeed:
    with _registry_lock:
        key = ("ts", n)
        if key not in _registry:
            _registry[key] = LiveFeed(n)
        return _registry[key]  # type: ignore[return-value]


def hls_feed(n: int) -> HLSFeed:
    with _registry_lock:
        key = ("hls", n)
        if key not in _registry:
            _registry[key] = HLSFeed(n)
        return _registry[key]  # type: ignore[return-value]


@functools.lru_cache(maxsize=8)
def _feed_loop(n: int, loop: int) -> bytes:
    return live_feed(n).build_loop(loop)


@functools.lru_cache(maxsize=96)
def _hls_segment(n: int, j: int) -> bytes:
    return hls_feed(n).build_segment(j)


