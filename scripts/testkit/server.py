def parse_timeshift_start(text: str) -> float | None:
    """`YYYY-MM-DD:HH-MM` (Xtream timeshift) in server-local time -> epoch."""
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})[:_ ](\d{2})[-:](\d{2})(?:[-:](\d{2}))?", text)
    if not m:
        return None
    y, mo, d, h, mi, s = (int(g) if g else 0 for g in m.groups())
    return time.mktime((y, mo, d, h, mi, s, 0, 0, -1))


class Handler(BaseHTTPRequestHandler):
    server_version = "TunerTestKit/1.0"

    def version_string(self):
        return self.server_version
    protocol_version = "HTTP/1.1"
    timeout = 120

    # -- plumbing ---------------------------------------------------------------------------------

    def log_message(self, format, *args):  # noqa: A002 - silence the default access log
        pass

    def log_request(self, code="-", size="-"):
        pass

    def do_GET(self):
        self._dispatch(head=False)

    def do_HEAD(self):
        self._dispatch(head=True)

    def _dispatch(self, head: bool):
        self.is_head = head
        self.headers_out = False
        split = urllib.parse.urlsplit(self.path)
        self.route_path = urllib.parse.unquote(split.path)
        self.query = dict(urllib.parse.parse_qsl(split.query, keep_blank_values=True))
        try:
            route(self)
        except CLIENT_GONE:
            self.close_connection = True
        except MediaMissing as e:
            if not self.headers_out:
                self.send_text(503, f"Test media not generated ({e}). Run scripts/testkit/make_media.sh first.\n")
            else:
                self.close_connection = True
        except Exception:  # noqa: BLE001
            traceback.print_exc()
            self.close_connection = True
            if not self.headers_out:
                try:
                    self.send_text(500, "internal error\n")
                except Exception:  # noqa: BLE001
                    pass

    def end_headers(self):
        self.headers_out = True
        super().end_headers()

    @property
    def host_port(self) -> tuple[str, str]:
        host = self.headers.get("Host", "")
        m = re.fullmatch(r"([A-Za-z0-9.\-]+|\[[0-9A-Fa-f:.]+\])(?::(\d{1,5}))?", host)
        if m:
            return m.group(1), m.group(2) or "80"
        h = CONFIG["host"] if CONFIG["host"] not in ("0.0.0.0", "::", "") else "127.0.0.1"
        return h, str(CONFIG["port"])

    @property
    def base(self) -> str:
        host, port = self.host_port
        return f"http://{host}" + ("" if port == "80" else f":{port}")

    def log(self, status: int, note: str = "") -> None:
        ua = self.headers.get("User-Agent", "-")
        ua = ua if len(ua) <= 48 else ua[:45] + "..."
        method = "HEAD" if self.is_head else "GET "
        rng = self.headers.get("Range")
        extra = f" [{note}]" if note else ""
        extra += f" Range:{rng.replace('bytes=', '')}" if rng and status in (200, 206, 416) else ""
        log(f"{status} {method} {self.path}{extra}  UA={ua}")

    # -- responses --------------------------------------------------------------------------------

    def respond(self, status: int, body: bytes, ctype: str, headers=(), note: str = ""):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        self.log(status, note)
        if not self.is_head:
            self.wfile.write(body)

    def send_text(self, status: int, text: str, note: str = ""):
        self.respond(status, text.encode(), "text/plain; charset=utf-8", note=note or text.strip().split("\n")[0][:80])

    def send_json(self, obj, note: str = ""):
        # PHP's json_encode escapes slashes and non-ASCII; mimic it.
        body = json.dumps(obj, ensure_ascii=True, separators=(",", ":")).replace("/", "\\/").encode()
        self.respond(200, body, "application/json; charset=utf-8", note=note)

    def send_ranged(self, size: int, reader, ctype: str, note: str = "", headers=()):
        status, start, end = 200, 0, size - 1
        header = self.headers.get("Range")
        if header and size > 0:
            r = parse_range(header, size)
            if r == "invalid":
                self.send_response(416)
                self.send_header("Content-Range", f"bytes */{size}")
                self.send_header("Content-Length", "0")
                self.end_headers()
                self.log(416, note)
                return
            if r:
                status, (start, end) = 206, r
        length = max(0, end - start + 1)
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(length))
        self.send_header("Accept-Ranges", "bytes")
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        self.log(status, note)
        if self.is_head or length == 0:
            return
        for chunk in reader(start, length):
            self.wfile.write(chunk)

    def send_file(self, path: Path, note: str = ""):
        if not path.is_file():
            if not MEDIA.is_dir():
                raise MediaMissing(f"{MEDIA} does not exist")
            return self.send_text(404, f"not found: {path.name}\n")
        size = path.stat().st_size
        ctype = CONTENT_TYPES.get(path.suffix.lower(), "application/octet-stream")

        def reader(start, length):
            with path.open("rb") as f:
                f.seek(start)
                while length > 0:
                    chunk = f.read(min(262_144, length))
                    if not chunk:
                        break
                    length -= len(chunk)
                    yield chunk

        mtime = time.strftime("%a, %d %b %Y %H:%M:%S GMT", time.gmtime(path.stat().st_mtime))
        self.send_ranged(size, reader, ctype, note, headers=[("Last-Modified", mtime)])

    def send_bytes_ranged(self, data: bytes, ctype: str, note: str = "", headers=()):
        view = memoryview(data)
        self.send_ranged(len(data), lambda s, n: (view[s:s + n],), ctype, note, headers)

    # -- live / archive streaming -----------------------------------------------------------------

    def stream_live_ts(self, n: int, label: str, stall_after: float | None = None):
        global _active_streams
        feed = live_feed(n)
        ts = feed.ts
        abs_i = feed.join_point(time.time() - ANCHOR)
        self.send_response(200)
        self.send_header("Content-Type", "video/mp2t")
        self.send_header("Cache-Control", "no-cache, no-store")
        self.send_header("Connection", "close")
        self.end_headers()
        self.close_connection = True
        loop0, idx0 = divmod(abs_i, ts.n)
        behind = (time.time() - ANCHOR) - (loop0 * feed.period + ts.pkt_time[idx0])
        self.log(200, f"{label} feed={n} live-ts join={behind:.1f}s behind live, loop {loop0}"
                      + (f", will stall after {stall_after:.0f}s" if stall_after else ""))
        if self.is_head:
            return
        t0, sent, reason = time.time(), 0, "client closed"
        with _active_lock:
            _active_streams += 1
        try:
            while True:
                now = time.time()
                if stall_after is not None and now - t0 >= stall_after:
                    log(f"... STALL {self.path}: stopped sending after {now - t0:.0f}s (socket kept open 60s)")
                    time.sleep(60)
                    reason = "stall finished"
                    break
                loop, idx = divmod(abs_i, ts.n)
                rel = (now - ANCHOR + LIVE_LEAD) - loop * feed.period
                end = min(bisect.bisect_right(ts.pkt_time, rel), idx + 2000)
                if end <= idx:
                    time.sleep(0.03)
                    continue
                data = feed.loop_bytes(loop)
                self.wfile.write(memoryview(data)[idx * TS_PACKET:end * TS_PACKET])
                sent += (end - idx) * TS_PACKET
                abs_i += end - idx
        except CLIENT_GONE:
            pass
        finally:
            with _active_lock:
                _active_streams -= 1
            log(f"END {self.path}: {time.time() - t0:.1f}s, {fmt_bytes(sent)} ({reason})")

    def serve_archive(self, n: int, ext: str, start: float, seconds: float, label: str):
        seconds = max(60.0, min(float(seconds), ARCHIVE_MAX))
        what = (f"{label} feed={n} archive start={fmt_utc(start)} "
                f"(server-local {time.strftime('%Y-%m-%d %H:%M', time.localtime(start))}) dur={seconds / 60:.0f}min")
        if ext == "m3u8":
            hf = hls_feed(n)
            first = hf.segment_at(start - ANCHOR)
            count = max(1, math.ceil(seconds / (hf.period / hf.count)))
            body = hf.playlist(first, count, live=False, media_sequence=0).encode()
            return self.respond(200, body, CONTENT_TYPES[".m3u8"], [("Cache-Control", "no-cache")], note=what + " vod-hls")
        feed = live_feed(n)
        abs0 = feed.join_point(start - ANCHOR)
        packets = math.ceil(seconds / feed.period * feed.ts.n)
        size = packets * TS_PACKET
        first_byte = abs0 * TS_PACKET

        def reader(pos, length):
            absolute = first_byte + pos
            while length > 0:
                loop, off = divmod(absolute, feed.loop_size)
                take = min(length, feed.loop_size - off)
                yield memoryview(feed.loop_bytes(loop))[off:off + take]
                absolute += take
                length -= take

        self.send_ranged(size, reader, "video/mp2t", note=what + f" {fmt_bytes(size)}")

    def serve_feed(self, n: int, ext: str, label: str, flaky: bool = False):
        if n not in FEEDS:
            return self.send_text(404, f"no such channel {n}\n")
        utc = self.query.get("utc") or self.query.get("start")
        if utc and re.fullmatch(r"\d+(\.\d+)?", utc):
            start, now = float(utc), time.time()
            if start < now - 30:
                lutc = self.query.get("lutc") or self.query.get("end")
                end = float(lutc) if lutc and re.fullmatch(r"\d+(\.\d+)?", lutc) else now
                return self.serve_archive(n, ext, start, end - start, label)
        if ext == "m3u8":
            hf = hls_feed(n)
            last = hf.segment_at(time.time() - ANCHOR) - 1     # newest *complete* segment
            first = last - HLS_WINDOW + 1
            body = hf.playlist(first, HLS_WINDOW, live=True, media_sequence=first).encode()
            return self.respond(200, body, CONTENT_TYPES[".m3u8"], [("Cache-Control", "no-cache")],
                                note=f"{label} feed={n} live-hls seq={first}")
        return self.stream_live_ts(n, label, stall_after=float(self.query.get("after", FLAKY_STALL_AFTER)) if flaky else None)


class TestKitServer(ThreadingHTTPServer):
    daemon_threads = True

    def handle_error(self, request, client_address):
        # Clients (players, ffprobe) routinely drop keep-alive or streaming sockets; don't dump tracebacks.
        if isinstance(sys.exc_info()[1], CLIENT_GONE + (ConnectionError,)):
            return
        super().handle_error(request, client_address)


