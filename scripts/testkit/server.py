def preload() -> None:
    for n in FEEDS:
        try:
            t0 = time.time()
            f, hf = live_feed(n), hls_feed(n)
            _feed_loop(n, math.floor((time.time() - ANCHOR) / f.period))
            log(f"feed {n} ({FEEDS[n]['name']}): ts {fmt_bytes(f.loop_size)}, loop {f.period:.2f}s, "
                f"{len(f.ts.keyframes)} keyframes; hls {hf.count} segs / {hf.period:.2f}s "
                f"(scanned in {time.time() - t0:.1f}s)")
        except MediaMissing as e:
            log(f"feed {n}: media missing ({e}) — run scripts/testkit/make_media.sh")
        except Exception as e:  # noqa: BLE001
            log(f"feed {n}: failed to load: {e}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Tuner local IPTV test server")
    ap.add_argument("port", nargs="?", type=int, default=int(os.environ.get("TESTKIT_PORT", DEFAULT_PORT)))
    ap.add_argument("--host", default=os.environ.get("TESTKIT_HOST", DEFAULT_HOST))
    args = ap.parse_args()
    CONFIG.update(host=args.host, port=args.port)

    server = TestKitServer((args.host, args.port), Handler)
    shown = args.host if args.host not in ("0.0.0.0", "::") else "127.0.0.1"
    base = f"http://{shown}:{args.port}"
    print(index_page(base), flush=True)
